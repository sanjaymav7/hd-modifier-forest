"""Every number in the README comes from this script.

    python3 run.py        (downloads ~75 MB from GEO on first run; ~10 min)

Writes docs/results.md and docs/auc_{light,dark}.svg.
"""
import warnings
warnings.filterwarnings("ignore")

import numpy as np
import pandas as pd
from scipy.stats import spearmanr
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import roc_auc_score
from sklearn.model_selection import GridSearchCV, StratifiedKFold, cross_val_predict, train_test_split

from hdrf.data import load_gse24250, load_gse51799, load_gse64810
from hdrf.model import GRID, nested_auc, notebook_pipeline

REPEATS = 5
out = []


def say(s=""):
    print(s, flush=True)
    out.append(s)


def age_only_auc(age, y, repeats=REPEATS):
    """Out-of-fold AUC of a logistic regression on age alone: the bar any expression model has to clear."""
    return np.mean([roc_auc_score(y, cross_val_predict(
        LogisticRegression(), np.asarray(age).reshape(-1, 1), y,
        cv=StratifiedKFold(5, shuffle=True, random_state=r), method="predict_proba")[:, 1])
        for r in range(repeats)])


def bh(p):
    p = np.asarray(p); o = np.argsort(p); n = len(p)
    q = np.empty(n); q[o] = np.minimum.accumulate((p[o] * n / np.arange(1, n + 1))[::-1])[::-1]
    return np.minimum(q, 1)


rows = []   # (setup, n, auc mean, auc sd, age-only auc)

# --- 1. The original notebook: GSE24250 only, one 70/30 split -------------------------------
e24, m24 = load_gse24250()
X24, y24 = e24.T.values, m24.label.values
split_aucs = []
for seed in range(20):
    Xtr, Xte, ytr, yte = train_test_split(X24, y24, test_size=0.3, stratify=y24, random_state=seed)
    gs = GridSearchCV(notebook_pipeline(), GRID, scoring="roc_auc",
                      cv=StratifiedKFold(3, shuffle=True, random_state=0), n_jobs=-1).fit(Xtr, ytr)
    split_aucs.append(roc_auc_score(yte, gs.predict_proba(Xte)[:, 1]))
r24 = nested_auc(X24, y24, repeats=REPEATS)
rows.append(("Blood, GSE24250 only (the notebook's data)", 14, r24["aucs"].mean(), r24["aucs"].std(),
             age_only_auc(m24.age, y24)))

# --- 2. Blood, the RNA-seq cohort the notebook couldn't parse --------------------------------
e51, m51 = load_gse51799()
y51 = m51.label.values
cov51 = m51[["age", "female", "hb_percentage"]].values
r51 = nested_auc(np.column_stack([e51.T.values, cov51]), y51, n_cov=3, repeats=REPEATS)
rows.append(("Blood, GSE51799, adjusted for age/sex/Hb%", 124, r51["aucs"].mean(), r51["aucs"].std(),
             age_only_auc(m51.age, y51)))

# --- 3. Brain: where the disease is -----------------------------------------------------------
eb, mb = load_gse64810()
yb = mb.label.values
covb = mb[["age", "rin", "pmi"]].values
rb_raw = nested_auc(eb.T.values, yb, repeats=REPEATS)
rb = nested_auc(np.column_stack([eb.T.values, covb]), yb, n_cov=3, repeats=REPEATS)
rows.append(("Brain BA9, GSE64810, unadjusted", 69, rb_raw["aucs"].mean(), rb_raw["aucs"].std(),
             age_only_auc(mb.age, yb)))
rows.append(("Brain BA9, GSE64810, adjusted for age/RIN/PMI", 69, rb["aucs"].mean(), rb["aucs"].std(),
             age_only_auc(mb.age, yb)))

say("# Results\n")
say(f"Generated by `python3 run.py`. Nested cross-validation: 5 outer folds × {REPEATS} repeats; "
    "hyperparameters tuned by an inner GridSearchCV that never sees the outer test fold. "
    "Covariates are regressed out inside each training fold.\n")
say("| Setup | n | Held-out AUC | Age alone |\n|:--|--:|--:|--:|")
for name, n, a, s, ag in rows:
    say(f"| {name} | {n} | {a:.3f} ± {s:.3f} | {ag:.3f} |")
say(f"\nThe notebook's own evaluation (one stratified 70/30 split of GSE24250) gives AUC between "
    f"{min(split_aucs):.2f} and {max(split_aucs):.2f} across 20 random seeds, mean {np.mean(split_aucs):.2f}: "
    "with 4–5 test samples, the split decides the score.\n")

# Blood by disease stage, using the adjusted model's out-of-fold probabilities
manifest = m51.motor_score > 5
say("Blood, by stage (out-of-fold probabilities from the adjusted GSE51799 model):\n")
say("| Comparison | n | AUC |\n|:--|--:|--:|")
for name, mask in [("manifest carriers vs controls", (y51 == 0) | (manifest & (y51 == 1))),
                   ("premanifest carriers vs controls", (y51 == 0) | (~manifest & (y51 == 1)))]:
    say(f"| {name} | {mask.sum()} | {roc_auc_score(y51[mask], r51['prob'][mask]):.3f} |")

# --- 4. Gene ranking from the adjusted brain model, then the modifier tests -------------------
genes = eb.index.values
rank = pd.DataFrame({"gene": genes, "kept": rb["kept"], "importance": rb["importance"]})
rank["score"] = rank["kept"] * rank["importance"]
top = rank.sort_values("score", ascending=False).head(20).reset_index(drop=True)

hd = mb.label == 1
onset = pd.to_numeric(mb.loc[hd, "age of onset"], errors="coerce")
cag = mb.loc[hd, "cag_repeats"]
ok = onset.notna() & cag.notna()
# Residual age of onset: how much earlier or later than CAG length predicts (log-onset on CAG, OLS).
b1, b0 = np.polyfit(cag[ok], np.log(onset[ok]), 1)
resid_onset = np.log(onset[ok]) - (b0 + b1 * cag[ok])
r_cag_onset = spearmanr(cag[ok], onset[ok])[0]

adj = eb.T.copy()
C = np.column_stack([np.ones(len(mb)), mb[["age", "rin", "pmi"]].fillna(mb[["age", "rin", "pmi"]].median()).values])
beta, *_ = np.linalg.lstsq(C[hd.values], adj[hd.values].values, rcond=None)
adj_hd = pd.DataFrame(adj[hd.values].values - C[hd.values][:, 1:] @ beta[1:], index=adj.index[hd.values], columns=adj.columns)

stats = []
for g in top.gene:
    rc, pc = spearmanr(adj_hd.loc[cag.index[cag.notna()], g], cag[cag.notna()])
    ro, po = spearmanr(adj_hd.loc[resid_onset.index, g], resid_onset)
    hd_up = eb.loc[g, hd.values].mean() > eb.loc[g, ~hd.values].mean()
    stats.append((rc, pc, ro, po, "up" if hd_up else "down"))
top[["rho_cag", "p_cag", "rho_resid_onset", "p_resid_onset", "in_HD"]] = pd.DataFrame(stats)
top["q_cag"], top["q_resid_onset"] = bh(top.p_cag), bh(top.p_resid_onset)

say(f"\n## Top 20 genes, brain model (adjusted)\n")
say(f"Ranked by (fraction of {len(rb['aucs'])} outer folds whose tuned model kept the gene) × "
    f"(mean forest importance). Within the 20 HD brains, expression is adjusted for age, RIN and PMI and "
    f"tested against CAG length and against residual age of onset (onset relative to what CAG predicts; "
    f"CAG vs onset here: ρ = {r_cag_onset:.2f}, n = {ok.sum()}). q = Benjamini-Hochberg over the 20 genes.\n")
say("| Gene | In HD | Kept | ρ vs CAG | q | ρ vs residual onset | q |\n|:--|:--|--:|--:|--:|--:|--:|")
for _, r in top.iterrows():
    say(f"| {r.gene} | {r.in_HD} | {r.kept:.0%} | {r.rho_cag:+.2f} | {r.q_cag:.2f} | "
        f"{r.rho_resid_onset:+.2f} | {r.q_resid_onset:.2f} |")

# --- 5. Do the brain genes carry into blood? --------------------------------------------------
blood_genes = [g for g in top.gene if g in e51.index]
sign = np.where(top.set_index("gene").loc[blood_genes, "in_HD"] == "up", 1, -1)
Z = e51.loc[blood_genes]; Z = Z.sub(Z.mean(1), axis=0).div(Z.std(1) + 1e-9, axis=0)
transfer = roc_auc_score(y51, (Z.values * sign[:, None]).mean(0))
say(f"\n## Brain to blood\n\n{len(blood_genes)} of the 20 brain genes are measured in GSE51799. "
    f"Scored in blood with their brain direction, they separate carriers from controls at AUC {transfer:.3f}.")

open("docs/results.md", "w").write("\n".join(out) + "\n")

